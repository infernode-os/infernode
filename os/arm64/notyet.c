/*
 * Halt. Upstream reboots or returns to a monitor; there is nowhere to
 * return to here, so stop the core with interrupts masked rather than
 * spinning.
 */
void
exit(int code)
{
	USED(code);
	print("\nkernel exit\n");
	splhi();
	for(;;)
		__asm__ volatile("wfi");
}




