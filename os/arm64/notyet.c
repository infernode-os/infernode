/*
 * The IP protocol table.
 *
 * Normally GENERATED by os/port/mkdevc from the "ip" section of a
 * kernel configuration, exactly as devtab and modinit are. Written by
 * hand until that build machinery exists, and kept here beside them so
 * it stays obvious all three are placeholders of the same kind.
 *
 * ipgetfs() walks this list once per IP stack, after ip_init(),
 * arpinit() and netloginit(), which it calls directly. Order within
 * the list does not matter -- each entry registers its own Proto.
 *
 * Nil-terminated: devip.c loops "for(i = 0; ipprotoinit[i]; i++)".
 *
 * tcp and udp are NOT here yet. They are imported last on purpose:
 * tcp.c's sequence comparisons survive LP64 by accident through (int)
 * truncation, which passes a smoke test and stalls under real traffic,
 * so it wants the same treat-it-as-hostile handling iproute.c got.
 */
void	ipifcinit(Fs*);
void	icmpinit(Fs*);
void	icmp6init(Fs*);
void	tcpinit(Fs*);
void	udpinit(Fs*);

void (*ipprotoinit[])(Fs*) =
{
	/*
	 * ipifc FIRST, and it is not optional. It registers the protocol
	 * that OWNS interfaces -- binding a medium, assigning addresses,
	 * the routes that follow from them -- so without it #I has no
	 * ipifc directory and there is no way to bring an interface up at
	 * all. ip_init() does not call it; upstream expects the kernel
	 * configuration to list it, which is what this table stands in
	 * for.
	 */
	ipifcinit,
	icmpinit,		/* ping, and the errors every other layer needs */
	icmp6init,		/* not optional: the v6 core calls into it */
	udpinit,
	tcpinit,
	nil,
};

