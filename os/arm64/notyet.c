/*
 * modinit -- register the built-in Dis modules.
 *
 * Normally GENERATED by os/port/mkdevc from the "mod" section of the
 * kernel configuration, which for os/pc lists sys, draw, tk, keyring and
 * math. Only sys is built here: the others need their own
 * limbo-generated headers and pull in the whole graphics and crypto
 * stack, none of which a first boot needs.
 *
 * sysmodinit() is what makes the Sys module callable from Dis. Without
 * it a Limbo program cannot open a file or write to the console.
 */
extern void sysmodinit(void);

void
modinit(void)
{
	sysmodinit();
}


