/*
 * A console on the framebuffer.
 *
 * The panel has worked since the mailbox cache fix, and until now it has
 * shown one test pattern and nothing else: every line the kernel printed
 * went to the serial port alone. putstrn0 already calls screenputs when
 * one is installed, so a console here needs no changes to devcons -- it
 * needs a screenputs, a font, and consoleprint set, which defaulted to 0.
 *
 * THE FONT is 8x16, rasterised from Menlo at the size whose advance is
 * exactly 8 pixels, and checked by rendering glyphs back to ASCII art
 * before being embedded rather than trusted. Only ASCII 32..126 is
 * carried: this is a kernel console, and a missing glyph prints as a
 * space rather than as a fault.
 *
 * It draws directly and synchronously. That is the right trade for a
 * console whose whole purpose is to still be working when other things
 * are not -- the same reason the serial port is polled.
 */

