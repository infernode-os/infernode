static Fbinfo *cons;
static int cx, cy;		/* cursor, in pixels */

static void
fbcls(void)
{
	fbfill(cons, Bg);
	cx = 0;
	cy = 0;
}

/*
 * Move everything up one line and clear the last.
 *
 * A whole-screen move per line is not clever, and at 800x480 it is about
 * 1.5MB -- which at this resolution costs less than any of the
 * alternatives cost in complexity, and a console that scrolls slowly is
 * still a console.
 */
static void
fbscroll(void)
{
	uchar *base;
	ulong linebytes, movebytes;
	int y, x, stride;
	volatile u32int *p;

	base = (uchar*)cons->base;
	linebytes = cons->pitch * Fh;
	movebytes = cons->pitch * (cons->height - Fh);

	memmove(base, base + linebytes, movebytes);

	stride = (int)(cons->pitch / 4);
	p = (volatile u32int*)(base + movebytes);
	for(y = 0; y < Fh; y++)
		for(x = 0; x < (int)cons->width; x++)
			p[y * stride + x] = Bg;

	cy -= Fh;
	if(cy < 0)
		cy = 0;
}

static void
fbglyph(int c)
{
	uchar *g;
	int y, x, stride;
	volatile u32int *p;

	if(c < Flo || c > Fhi)
		c = ' ';
	g = font[c - Flo];

	stride = (int)(cons->pitch / 4);
	p = (volatile u32int*)cons->base;
	for(y = 0; y < Fh; y++){
		if(cy + y >= (int)cons->height)
			break;
		for(x = 0; x < Fw; x++){
			if(cx + x >= (int)cons->width)
				break;
			if(g[y] & (0x80 >> x))
				p[(cy + y) * stride + cx + x] = Fg;
		}
	}
}

void
fbconsputs(char *s, int n)
{
	int i, c;

	if(cons == nil)
		return;

	for(i = 0; i < n; i++){
		c = s[i] & 0xFF;
		switch(c){
		case '\n':
			cx = 0;
			cy += Fh;
			break;
		case '\r':
			cx = 0;
			break;
		case '\t':
			cx = (cx / (Fw * 8) + 1) * (Fw * 8);
			break;
		case '\b':
			if(cx >= Fw)
				cx -= Fw;
			break;
		default:
			if(c < Flo || c > Fhi)
				break;
			fbglyph(c);
			cx += Fw;
			break;
		}
		if(cx + Fw > (int)cons->width){
			cx = 0;
			cy += Fh;
		}
		while(cy + Fh > (int)cons->height)
			fbscroll();
	}
}

/*
 * Take over the screen. Returns 0 if there is one to take over.
 */
int
fbconsinit(Fbinfo *fb)
{
	if(fb == nil || fb->base == 0 || fb->pitch == 0)
		return -1;
	if(fb->depth != 32)		/* the glyph writer assumes it */
		return -1;

	cons = fb;
	fbcls();
	return 0;
}
