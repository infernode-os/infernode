/*
 * The console can drive more than one screen.
 *
 * A Raspberry Pi with the 7in DSI panel attached has TWO displays, and
 * the firmware makes the panel the default -- so a machine with a
 * monitor plugged into HDMI and a panel on the ribbon showed its
 * console only on the panel, and the monitor sat on the firmware's
 * rainbow. Most people do not own the panel, so HDMI is the display
 * that matters most, and the console has to reach both.
 *
 * Each screen keeps its OWN cursor and its own geometry, and the same
 * stream of runes is drawn on all of them. That is mirroring in the
 * sense that matters -- the same content is on every display -- without
 * pretending the displays are the same shape.
 *
 * The alternative was tried and is worse: one shared cursor clamped to
 * the smallest screen. A 1024x768 monitor beside an 800x480 panel then
 * uses a corner of the monitor, and the panel is laid out for a screen
 * it is not, which on real glass looked like smeared text. A console
 * that wraps at each display's own width costs a cursor per screen and
 * looks right on both.
 */
typedef struct Screen Screen;
struct Screen
{
	Fbinfo	*fb;
	int	voff;		/* where the visible window sits in the buffer */
	int	w, h;		/* what this screen gives the console */
	int	cx, cy;		/* this screen's cursor, in pixels */
	int	hwscroll;	/* firmware will move the window for us */
	int	vh;		/* usable scanlines in the allocation */
	int	scrollpix;	/* how far one scroll moves this screen */
};

static Screen screens[Maxscreens];
static int nscreens;

/*
 * Set once the draw device has taken the framebuffer, and never
 * cleared.
 *
 * The count of screens cannot answer "is the console still running",
 * because stopping sets it to zero -- which reads exactly like "no
 * screens yet" to anything that might add one. The display watcher
 * asked precisely that question and got precisely that wrong answer:
 * after a draw client attached, it saw no screens, decided the second
 * display was not connected yet, and installed a text console back on
 * top of the window system's framebuffer -- once per poll.
 */
static int released;

/*
 * One writer OR the release, never both. The scanout offset is shared
 * state between every console print (a scroll moves it) and the
 * moment the draw device takes the screen (which must put it back to
 * zero and KEEP it there). Without exclusion, a print already inside
 * this file on another core scrolls after the reset, and the glass
 * shows a console window under a freshly painted login screen --
 * found by a person at the panel after every software check said the
 * screen was fine. Bounded _tas like the uart mutex, so a panic can
 * still print through a dead holder: garbled beats silent.
 */
static ulong fbmutex;

static int
fbconslock(void)
{
	int i;

	/*
	 * Time-scaled, not iteration-scaled: the holder may be mid
	 * scroll-fold, a 1.5MB memmove plus a mailbox call that takes
	 * tens of milliseconds. An iteration bound sized for a quick
	 * glyph declared that holder stuck, released the screen
	 * underneath it, and its final scroll moved the scanout right
	 * back off the login screen -- the same class of premature
	 * tripwire as the UP-era lock bounds.
	 */
	for(i = 0; i < 500; i++){
		if(_tas(&fbmutex) == 0)
			return 1;
		microdelay(1000);
	}
	return 0;	/* print anyway; do not wedge a panic */
}

static void
fbconsunlock(void)
{
	coherence();
	fbmutex = 0;
}

/*
 * Clear virtual scanlines [y0, y0+nl) on one screen.
 */
static void
fbclearlines(Screen *s, int y0, int nl)
{
	int y, x, stride;
	volatile u32int *p;

	stride = (int)(s->fb->pitch / 4);
	p = (volatile u32int*)s->fb->base;
	for(y = y0; y < y0 + nl; y++)
		for(x = 0; x < (int)s->fb->width; x++)
			p[y * stride + x] = Bg;
}

static void
fbcls(void)
{
	int i;

	for(i = 0; i < nscreens; i++){
		fbfill(screens[i].fb, Bg);
		screens[i].voff = 0;
		screens[i].cx = 0;
		screens[i].cy = 0;
		if(screens[i].hwscroll){
			mboxfbdispnum(screens[i].fb->disp);
			mboxfbvoff(0, 0);
		}
	}
}

/*
 * Scroll one screen, moving the window if the firmware will and copying
 * pixels if it will not.
 */
static void
screenscroll(Screen *s)
{
	static int folded;
	uchar *base;
	ulong linebytes, movebytes;
	int y, x, stride, newcy;

	base = (uchar*)s->fb->base;
	newcy = s->cy - s->scrollpix;
	if(newcy < 0)
		newcy = 0;

	if(s->hwscroll){
		if(s->voff + s->h + s->scrollpix > s->vh){
			/*
			 * Fold: the window is as far down the buffer as it
			 * goes, so the visible content moves back to the
			 * top. This is the whole-screen move that used to
			 * happen for every line; it now happens once per
			 * screenful.
			 */
			if(!folded){
				folded = 1;
				uartputstr("fb:   window folded once\n");
			}
			memmove(base, base + (ulong)s->voff * s->fb->pitch,
				(ulong)s->h * s->fb->pitch);
			s->voff = 0;
			mboxfbdispnum(s->fb->disp);
			mboxfbvoff(0, 0);
		}
		s->voff += s->scrollpix;

		if(s->voff + newcy + s->scrollpix > s->vh
		|| s->voff + s->h > s->vh){
			uartputstr("fb:   SCROLL OUT OF RANGE, reverting to copy\n");
			s->hwscroll = 0;
			s->voff = 0;
			mboxfbdispnum(s->fb->disp);
			mboxfbvoff(0, 0);
			s->cy = newcy;
			return;
		}

		fbclearlines(s, s->voff + newcy, s->scrollpix);

		/*
		 * Select the display before moving its window: the offset
		 * tag applies to whichever display the firmware has
		 * current, so with two screens the second one's offset
		 * would otherwise be written to the first.
		 */
		mboxfbdispnum(s->fb->disp);
		mboxfbvoff(0, s->voff);
		s->cy = newcy;
		return;
	}

	/* the slow path: move the pixels */
	linebytes = s->fb->pitch * (ulong)s->scrollpix;
	if(linebytes > s->fb->pitch * (ulong)s->h)
		linebytes = s->fb->pitch * (ulong)s->h;
	movebytes = s->fb->pitch * (ulong)s->h - linebytes;

	memmove(base, base + linebytes, movebytes);

	stride = (int)(s->fb->pitch / 4);
	{
		volatile u32int *p;

		p = (volatile u32int*)(base + movebytes);
		for(y = 0; y < s->scrollpix && s->cy - y > 0; y++)
			for(x = 0; x < s->w; x++)
				p[y * stride + x] = Bg;
	}
	s->cy = newcy;
}

/*
 * Blank the character cell one screen's cursor is on.
 */
static void
screenclearcell(Screen *s)
{
	int y, x, stride;
	volatile u32int *p;

	stride = (int)(s->fb->pitch / 4);
	p = (volatile u32int*)s->fb->base;
	for(y = 0; y < Fh; y++){
		if(s->cy + y >= s->h)
			break;
		for(x = 0; x < Fw; x++){
			if(s->cx + x >= s->w)
				break;
			p[(s->voff + s->cy + y) * stride + s->cx + x] = Bg;
		}
	}
}

/*
 * The glyph for a rune, or nil if there is not one.
 */
static uchar*
fbfindglyph(Rune r)
{
	if(r >= Flo && r <= Fhi)
		return font[r - Flo];
	if(r >= 0xA0 && r <= 0xFF)
		return latin1font[r - 0xA0];
	return nil;
}

static void
screenglyph(Screen *s, uchar *g)
{
	int y, x, stride;
	volatile u32int *p;

	stride = (int)(s->fb->pitch / 4);
	p = (volatile u32int*)s->fb->base;
	for(y = 0; y < Fh; y++){
		if(s->cy + y >= s->h)
			break;
		for(x = 0; x < Fw; x++){
			if(s->cx + x >= s->w)
				break;
			if(g[y] & (0x80 >> x))
				p[(s->voff + s->cy + y) * stride + s->cx + x] = Fg;
		}
	}
}

/*
 * One rune onto one screen, advancing that screen's cursor.
 */
static void
screenputrune(Screen *s, Rune r, uchar *g)
{
	switch(r){
	case '\n':
		s->cx = 0;
		s->cy += Fh;
		break;
	case '\r':
		s->cx = 0;
		break;
	case '\t':
		s->cx = (s->cx / (Fw * 8) + 1) * (Fw * 8);
		break;
	case '\b':
		/*
		 * Destructive, because here the console IS the terminal.
		 *
		 * devcons echoes the raw character -- it does not send the
		 * "\b \b" a program would use to rub a character out on a
		 * glass tty -- so if this only moved the cursor, nothing
		 * would ever be erased. That is exactly what it looked
		 * like: deletes were obeyed (the shell received "HEL"
		 * after "HELLO" and two backspaces) while the panel still
		 * showed all five letters.
		 */
		if(s->cx >= Fw){
			s->cx -= Fw;
			screenclearcell(s);
		}
		break;
	default:
		if(r < ' ')		/* other control characters */
			break;
		screenglyph(s, g);
		s->cx += Fw;
		break;
	}
	if(s->cx + Fw > s->w){
		s->cx = 0;
		s->cy += Fh;
	}
	while(s->cy + Fh > s->h)
		screenscroll(s);
}

/*
 * One rune onto every screen.
 *
 * The glyph is looked up ONCE and handed to each screen: it is the same
 * bitmap on all of them, and the lookup includes building the
 * "unrenderable" box, which there is no reason to do twice.
 */
static void
fbputrune(Rune r)
{
	uchar box[Fh];
	uchar *g;
	int i, y;

	g = fbfindglyph(r);
	if(g == nil){
		/*
		 * Show that something is there and cannot be drawn.
		 *
		 * Blank would be a lie -- it reads as a space, so a name
		 * with an unrenderable character in it looks like a
		 * different, valid name. A box says "a character, not in
		 * this font", which is what the reader needs to know.
		 */
		for(y = 0; y < Fh; y++)
			box[y] = 0;
		for(y = 3; y < Fh - 3; y++)
			box[y] = 0x42;
		box[3] = box[Fh - 4] = 0x7E;
		g = box;
	}

	for(i = 0; i < nscreens; i++)
		screenputrune(&screens[i], r, g);
}

/*
 * Text onto the screen, decoded as UTF-8.
 *
 * Byte at a time was ASCII-only, and silently so: a composed character
 * arrives as two bytes -- U+00E9 is C3 A9 -- and both were outside the
 * glyph range, so each was dropped and nothing appeared. Compose looked
 * broken when what was broken was the console's idea of a character.
 *
 * The carry matters. screenputs is called once per write, and a write
 * can end in the middle of a multi-byte sequence, so an incomplete tail
 * is held until the bytes that finish it arrive rather than being
 * discarded as malformed.
 */
void
fbconsputs(char *s, int n)
{
	static char pend[UTFmax];
	static int npend;
	Rune r;
	int i, k;
	int locked;

	if(nscreens == 0)
		return;

	locked = fbconslock();
	if(released){
		/* the draw device took the screen while we waited */
		if(locked)
			fbconsunlock();
		return;
	}

	for(i = 0; i < n; ){
		if(npend > 0){
			while(npend < UTFmax && i < n && !fullrune(pend, npend))
				pend[npend++] = s[i++];
			if(!fullrune(pend, npend)){
				if(locked)
					fbconsunlock();
				return;		/* still short; wait */
			}
			chartorune(&r, pend);
			npend = 0;
			fbputrune(r);
			continue;
		}
		if(!fullrune(s + i, n - i)){
			for(k = 0; i < n && k < UTFmax; k++)
				pend[k] = s[i++];
			npend = k;
			if(locked)
				fbconsunlock();
			return;
		}
		i += chartorune(&r, s + i);
		fbputrune(r);
	}
	if(locked)
		fbconsunlock();
}

/*
 * Add a screen for the console to draw on. Returns 0 if it took it.
 */
int
fbconsadd(Fbinfo *fb)
{
	Screen *s;
	int i;

	if(released)			/* the draw device owns the screen */
		return -1;
	if(fb == nil || fb->base == 0 || fb->pitch == 0)
		return -1;
	if(fb->depth != 32)		/* the glyph writer assumes it */
		return -1;
	if(nscreens >= Maxscreens)
		return -1;

	s = &screens[nscreens];
	s->fb = fb;
	s->voff = 0;
	s->vh = (int)(fb->size / fb->pitch);
	s->w = (int)fb->width;
	s->h = (int)fb->height;
#ifdef FBSCROLLTEST
	/*
	 * Give the console only half of this screen so the other half
	 * becomes the scrolling headroom.
	 *
	 * QEMU grants the offset but reports a screen-sized allocation,
	 * so the gate below -- correctly -- keeps the fast path off
	 * there, and the code that only runs on hardware would be the
	 * code no test ever touches. Halving makes the headroom real
	 * WITHIN the allocation the emulator did give us, so the offset
	 * arithmetic, the fold and the clearing all execute under test.
	 */
	s->h /= 2;
	s->h -= s->h % Fh;
#endif
	s->h -= s->h % Fh;

	/*
	 * Two things must hold before this screen's window may be moved,
	 * and only one of them is about scrolling.
	 *
	 * The buffer must be taller than the display, because once the
	 * window moves down, glyphs and cleared lines are written BELOW
	 * the visible height -- straight past the end of the allocation
	 * if the firmware quietly gave a screen-sized buffer anyway. That
	 * check is what keeps a refused request from turning into memory
	 * corruption, so it comes first, and the headroom is taken from
	 * the size REPORTED rather than the size asked for.
	 *
	 * Then the offset itself: accepting the tag is not the test,
	 * since a firmware with nowhere to move the window clamps the
	 * offset to zero and still reports success, and a console
	 * scrolled with an offset that never moves shows one screenful
	 * for ever. Ask for one line down and require that exact answer.
	 */
	s->hwscroll = 0;
	mboxfbdispnum(fb->disp);
	if(s->vh >= s->h + Fh && mboxfbvoff(0, Fh) == Fh)
		s->hwscroll = 1;
	mboxfbvoff(0, 0);

	/*
	 * One line at a time when the window can be moved, because that
	 * is free; several at a time when pixels have to be copied,
	 * because that is where the cost is. Per screen, since one
	 * display can have the fast path while the other does not.
	 */
	s->scrollpix = s->hwscroll? Fh : Fh * Scrolllines;

	nscreens++;

	uartputstr("fb:   console on display ");
	uartputd(fb->disp);
	uartputstr(", ");
	uartputd(s->w);
	uartputstr("x");
	uartputd(s->h);
	uartputstr(screens[nscreens-1].hwscroll?
		" (scroll by GPU offset)\n" : " (scroll by copy)\n");
	return 0;
}

/*
 * Take over the screen. Returns 0 if there is one to take over.
 */
int
fbconsinit(Fbinfo *fb)
{
	if(fbconsadd(fb) < 0)
		return -1;

	fbcls();

	/*
	 * Say so on the panel itself.
	 *
	 * Kept from the diagnostic that established this worked, because
	 * it is worth having: the first line on the screen is the one
	 * that proves the screen is a console rather than a surface
	 * something drew on once. It is also drawn from here, without
	 * devcons in the path, so it appears even if nothing else ever
	 * routes text this way.
	 */
	fbconsputs("InferNode console\n", 18);
	return 0;
}

/*
 * How many screens the console is drawing on.
 *
 * The display watcher needs to know whether it has already brought a
 * screen up, and nscreens is private to this file.
 */
int
fbconsscreens(void)
{
	return nscreens;
}

/*
 * Whether the framebuffer has been handed to the draw device. One way:
 * a console that has given the screen up does not take it back, because
 * a window system is drawing on it.
 */
int
fbconsreleased(void)
{
	return released;
}

/*
 * How far down the buffer the visible window currently sits.
 *
 * The console scrolls by moving the GPU's scanout offset, so the top of
 * the framebuffer is NOT what the panel is showing. Anything reading
 * the framebuffer back to see what a person sees has to add this --
 * screendump did not, and reported a blank screen while the console
 * was full of text.
 *
 * Zero once the draw device has the screen: fbconsstop puts the window
 * back before letting go.
 */
int
fbconsvoff(void)
{
	if(released || nscreens == 0)
		return 0;
	return screens[0].voff;
}

/*
 * Give up the framebuffer.
 *
 * Called when the draw device attaches: two things cannot own the same
 * pixels, and between a text console and a window system the window
 * system wins -- text scribbled over a compositor's output at
 * unpredictable moments is worse than no framebuffer console at all.
 *
 * Nothing is really lost. Kernel output has always gone to the serial
 * console as well, and that is unaffected; screenputs is cleared so
 * devcons stops calling here at all rather than calling into a function
 * that would only return.
 *
 * PUT THE SCANOUT WINDOW BACK FIRST, and this is not tidying.
 *
 * This console scrolls by moving the GPU's virtual offset rather than
 * by copying pixels: the buffer is twice the height of the display and
 * the visible window slides down it. After a boot's worth of messages
 * that window is a long way from the top.
 *
 * The draw device knows nothing about that. attachscreen hands it the
 * base of the buffer and it draws at 0,0 -- which is off the top of
 * what the panel is showing. Everything worked and nothing appeared:
 * the pixels were in the framebuffer, readpixels found them there
 * because it reads the same memory, and the screen showed a region of
 * the buffer nobody was drawing in.
 */
void
fbconsstop(void)
{
	int i, n;

	/*
	 * Stop the console FIRST, then reset the scanout offsets --
	 * in that order, with a barrier and a settle between.
	 *
	 * The other order lost the screen: a print in flight on another
	 * core could scroll and push the GPU offset back nonzero AFTER
	 * the reset here, and nothing ever resets it again -- the glass
	 * scans the old console window forever while the draw client
	 * paints, correctly, at offset zero. Software said login
	 * screen; the panel said frozen console; both were telling the
	 * truth about different offsets. Timing-dependent, so some
	 * boots worked and the ones with boot spew still streaming did
	 * not.
	 */
	if(!fbconslock())
		uartputstr("fb:   console writer stuck; releasing anyway\n");
	n = nscreens;
	screenputs = nil;
	released = 1;
	nscreens = 0;
	coherence();

	/*
	 * Secondary displays first, display 0 LAST -- the display-select
	 * tag is known unreliable, and ending on display 0 leaves the
	 * selector where the draw device and any later reset expect it.
	 * And VERIFIED: ask the firmware where the scanout actually is
	 * and retry until it answers zero, because a set that silently
	 * did not take is exactly how the glass kept showing a scrolled
	 * console under a freshly painted login screen.
	 */
	for(i = n - 1; i >= 0; i--){
		int t, gv;

		mboxfbdispnum(screens[i].fb->disp);
		for(t = 0; t < 5; t++){
			mboxfbvoff(0, 0);
			gv = mboxfbgetvoff();
			if(gv <= 0)
				break;
		}
		if(t == 5){
			uartputstr("fb:   display ");
			uartputd(screens[i].fb->disp);
			uartputstr(" scanout offset WILL NOT reset\n");
		}
		screens[i].voff = 0;
	}

	fbconsunlock();
	uartputstr("fb:   console released to the draw device\n");
}
