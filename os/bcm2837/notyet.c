/*
 * portclock.c -- called from inside a contended ilock spin.
 *
 * Upstream uses it to notice that the clock interrupt has been masked
 * for too long while spinning, and to run the timer callbacks that
 * would otherwise be starved. This port drives its tick from clock.c
 * rather than portclock.c's Timer machinery, and runs on one core where
 * a contended ilock means a deadlock rather than a wait -- so there is
 * nothing useful to do here yet, and taslock.c's spin limit is what
 * actually catches the deadlock.
 */
void
clockcheck(void)
{
}

/*
 * modinit -- register the built-in Dis modules.
 *
 * Normally GENERATED by os/port/mkdevc from the "mod" section of the
 * kernel configuration, which for os/pc lists sys, draw, tk, keyring and
 * math. Only sys is built here: the others need their own
 * limbo-generated headers and pull in the whole graphics and crypto
 * stack, none of which a first boot needs.
 *
 * sysmodinit() is what makes the Sys module callable from Dis. Without
 * it a Limbo program cannot open a file or write to the console.
 */
extern void sysmodinit(void);

void
modinit(void)
{
	sysmodinit();
}

/*
 * devprog.c -- format a Prog's current module and pc for /prog/N/status.
 * devprog is not imported; exception.c calls this when reporting where a
 * Dis exception was raised.
 */
WORD
modstatus(REG *r, char *ptr, int len)
{
	USED(r);
	if(len > 0)
		ptr[0] = 0;
	return 0;
}

