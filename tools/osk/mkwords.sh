# mkwords.sh — build lib/osk/en.words, the on-screen keyboard's English
# lexicon, lib/osk/en.pairs, the word pairs it predicts the next word
# from, and lib/osk/NOTICE, their attribution.
#
#   tools/osk/mkwords.sh [workdir]
#
# Vocabulary: SCOWL (Spell Checker Oriented Word Lists) 2020.12.07, the
# list `mk-list -v1 --accents=both en_US en_GB-ise en_GB-ize 60` makes:
# American and British spellings both ("behavior" and "behaviour",
# "recognized" and "recognised"), variants to level 1, sizes up to 60,
# proper names, abbreviations and contractions included, each accented
# word also without its accents.
# mkwords.py reimplements mk-list; nothing from the archive is run.
#
# Frequency: Google Books Ngram, version 3 (20200217), English,
# match_count summed over the years from 1980, matched case-sensitively
# to untagged ngrams.  A word is counted as its 1-gram and, if Google's
# tokenizer splits it, as its 2-gram: "it's" is `it 's`, "John's"
# `John 's`, "they're" `they 're`, "cannot" `can not` (mkwords.py keys);
# the 1-grams alone gave "it's" a thousandth of its count.  The
# tokenizer also made every "n't" "not", so "don't" is counted with
# "do not", which the data cannot tell from it.
#
# The 24 1-gram shards (13.4 GB) and 589 2-gram shards (324 GB) are
# streamed through the counter, never stored.  Each is checked against
# the MD5 Google's storage gives for it (its x-goog-hash; Google
# publishes no other checksum) and the SHA-256 recorded below.
#
# A SCOWL word the corpus never has is kept with a count of 1 if its
# size is at most 35, and dropped otherwise.  The 65000 most frequent
# are written, by count, scaled so the largest is the largest Limbo int.
#
# en.pairs: the untagged 2-grams both of whose words are en.words words,
# case folded ("The cat" counts as "the cat"), years from 1980, the
# 120000 most frequent, by first word and then count, scaled as the
# words are.  Its words are lower case.  A shard's 2-grams under 5000
# are not kept (mkwords.py pairs checks that cannot matter).  Clitics
# are not words, so `it 's` is no pair, and a pair with a contraction
# ("don't know") has only the uses the tokenizer left whole; counting
# the rest would take the 3-grams.
#
# Needs curl, tar, gzip and python3.  JOBS shards (default 4) are
# counted at once, each about a core's work: an hour with JOBS=6 on
# 4 cores and a 100 MB/s link.  A shard whose transfer breaks is
# fetched again.  The work directory (default a fresh one under
# TMPDIR) needs about 300 MB.

