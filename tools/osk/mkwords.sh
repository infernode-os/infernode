py() { python3 -I "$here/mkwords.py" "$@"; }

sha256() {
	python3 -I -c 'import hashlib,sys
h = hashlib.sha256()
with open(sys.argv[1], "rb") as f:
    for b in iter(lambda: f.read(1 << 20), b""):
        h.update(b)
print(h.hexdigest())' "$1"
}

say() { echo "mkwords: $*" >&2; }
fail() { say "$*"; exit 1; }

start=$(date +%s)
case $work in
*[[:space:]]*) fail "$work: the work directory's name has a blank" ;;
esac
mkdir -p "$work"
[ -z "$(ls -A "$work")" ] || fail "$work is not empty"
mkdir "$work/scowl" "$work/scowl/x" "$work/counts" "$work/pairs" "$work/log"

# SCOWL
tgz=$work/scowl/scowl-$SCOWL_VERSION.tar.gz
say "fetching SCOWL $SCOWL_VERSION"
curl -fsSL --retry 3 -o "$tgz" "$SCOWL_URL"
got=$(sha256 "$tgz")
[ "$got" = "$SCOWL_SHA256" ] || fail "SCOWL sha256 $got, want $SCOWL_SHA256"
if tar tzf "$tgz" | grep -q -e '^/' -e '\.\./'; then
	fail "SCOWL archive has a member outside its directory"
fi
tar xzf "$tgz" -C "$work/scowl/x"
scowl=$work/scowl/x/scowl-$SCOWL_VERSION
py vocab "$scowl/final" "$SCOWL_SIZE" >"$work/vocab"
py keys 1 "$work/vocab" >"$work/keys1"
py keys 2 "$work/vocab" >"$work/keys2"
say "vocabulary: $(wc -l <"$work/vocab") words," \
	"$(wc -l <"$work/keys2") of them split in two"

# Ngram shards, JOBS at a time
countshard() {	# n shard of md5 sha256
	name=$1-$2-of-$3
	pairs=
	if [ "$1" -eq 2 ]; then
		pairs="$work/vocab $work/pairs/$name.tmp $MIN_PAIR"
	fi
	for try in 1 2 3 4 5; do
		# $pairs unquoted: three words, or none; $work has no blanks
		if curl -fsS "$NGRAM_URL/$name.gz" |
		   py count "$work/keys$1" "$MIN_YEAR" "$4" "$5" $pairs \
			>"$work/counts/$name.tmp" 2>"$work/log/$name"
		then
			mv "$work/counts/$name.tmp" "$work/counts/$name"
			if [ -n "$pairs" ]; then
				mv "$work/pairs/$name.tmp" "$work/pairs/$name"
			fi
			say "$name done ($(($(date +%s) - start))s)" \
				"$(cat "$work/log/$name")"
			return 0
		fi
		say "$name failed (try $try): $(cat "$work/log/$name")"
	done
	return 1
}

worker() {	# k
	i=0
	shards | while read -r n s of md5 sha; do
		if [ $((i % JOBS)) -eq "$1" ]; then
			countshard "$n" "$s" "$of" "$md5" "$sha" || exit 1
		fi
		i=$((i + 1))
	done
}

say "counting $NSHARDS Ngram shards, $JOBS at a time"
k=0
pids=
while [ "$k" -lt "$JOBS" ]; do
	worker "$k" &
	pids="$pids $!"
	k=$((k + 1))
done
ok=1
for p in $pids; do
	wait "$p" || ok=0
done
[ "$ok" -eq 1 ] || fail "a shard could not be counted"
n=$(ls "$work/counts" | grep -c -e '-of-[0-9]*$' || :)
[ "$n" -eq "$NSHARDS" ] || fail "$n of $NSHARDS shards counted"

